def polygon(points):
    return 'M '+' L '.join(f'{x:g} {y:g}' for x,y in points)+' Z'
def rect(x,y,w,h): return polygon([(x,y),(x+w,y),(x+w,y+h),(x,y+h)])
def line(x,y,X,Y,w=12):
    dx,dy=X-x,Y-y; n=math.hypot(dx,dy); a,b=-dy*w/n/2,dx*w/n/2
    return polygon([(x+a,y+b),(X+a,Y+b),(X-a,Y-b),(x-a,y-b)])
def ellipse(cx,cy,rx,ry,reverse=False):
    k=.55228475
    s=-1 if reverse else 1
    p=f'M {cx+rx} {cy} C {cx+rx} {cy+s*k*ry} {cx+k*rx} {cy+s*ry} {cx} {cy+s*ry} C {cx-k*rx} {cy+s*ry} {cx-rx} {cy+s*k*ry} {cx-rx} {cy} C {cx-rx} {cy-s*k*ry} {cx-k*rx} {cy-s*ry} {cx} {cy-s*ry} C {cx+k*rx} {cy-s*ry} {cx+rx} {cy-s*k*ry} {cx+rx} {cy} Z'
    if reverse: HOLES.add(p)
    return p
