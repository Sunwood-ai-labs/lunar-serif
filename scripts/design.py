def main():
    from fontTools.pens.svgPathPen import SVGPathPen
    from fontTools.pens.transformPen import TransformPen
    from fontTools.svgLib.path import parse_path
    import pathops
    metadata={}
    for name,g in G.items():
        p=''
        # All solids share winding; only declared counters are holes. This avoids
        # accidental white seams where flared serifs overlap the main strokes.
        for raw in re.findall(r'M[^M]*?Z',g['path']):
            contour=pathops.Path(); parse_path(raw,contour.getPen())
            want_clockwise=raw in HOLES
            if contour.clockwise!=want_clockwise: contour.reverse()
            outline=SVGPathPen(None); contour.draw(outline); p+=outline.getCommands()
        if 'transform' in g:
            pen=SVGPathPen(None); parse_path(p,TransformPen(pen,g['transform'])); p=pen.getCommands()
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {g["width"]} 1100"><g transform="translate(0 820) scale(1 -1)"><path d="{p}" fill="black" fill-rule="nonzero"/></g></svg>\n'
        (ROOT/'sources/glyphs'/f'{name}.svg').write_text(svg,encoding='utf-8')
        metadata[name]={'char':g['char'],'advance':g['width']}
    (ROOT/'sources/metrics.json').write_text(json.dumps(metadata,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Wrote {len(G)} original SVG glyph sources.')
if __name__=='__main__': main()
